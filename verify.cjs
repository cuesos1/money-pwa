require('./calculator.js');
const {parseAmount, allocate, validPercentages, defaults} = globalThis.MoneyCalculator;
assert.equal(parseAmount('17 350,50'), 1735050);
assert.equal(parseAmount(''), 0);
assert.equal(parseAmount('0,01'), 1);
