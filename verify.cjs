for (const invalid of ['-1','1.234','1e3','abc','1,2,3','1000000000.01']) assert.equal(parseAmount(invalid), null);
for (const invalid of [[35,40,10,14],[35.5,39.5,10,15],[-1,41,10,50],[99,0,0],null]) assert.equal(validPercentages(invalid), false);
